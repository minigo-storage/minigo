#!/usr/bin/env bash
# Same-volume MinIO -> Minigo -> MinIO compatibility, against new test data only.
set -euo pipefail
umask 077
ROOT=$(cd "$(dirname "$0")/.." && pwd)
cd "$ROOT"
MODE=${1:-full}
BASELINE_IMAGE=${BASELINE_IMAGE:-minio/minio:RELEASE.2025-09-07T16-13-09Z}
TARGET_IMAGE=${TARGET_IMAGE:-minigo:local-arm64}
SMALL_OBJECTS=${SMALL_OBJECTS:-10000}
LARGE_BYTES=${LARGE_BYTES:-5369757696}
KEEP_VOLUME=${KEEP_VOLUME:-0}
COMPOSE_FILE="$ROOT/tests/compatibility/compose.yaml"

for tool in docker go mc openssl python3 curl; do command -v "$tool" >/dev/null || { echo "Required tool missing: $tool" >&2; exit 1; }; done
docker compose version >/dev/null

if [[ "$MODE" == resume || "$MODE" == prepare-resume ]]; then
  RUN_DIR=${2:?Pass the existing run directory to resume}
  RUN_DIR=$(cd "$RUN_DIR" && pwd)
  # Generated by this script with hexadecimal secrets and a controlled project name.
  # shellcheck disable=SC1091
  source "$RUN_DIR/private/environment"
else
  [[ "$MODE" == full || "$MODE" == prepare ]] || { echo 'Usage: scripts/test-compatibility.sh [full|prepare|resume RUN_DIR]' >&2; exit 1; }
  export COMPOSE_PROJECT_NAME MINIO_ROOT_USER MINIO_ROOT_PASSWORD COMPAT_IAM_SECRET
  COMPOSE_PROJECT_NAME="minigo-compat-$(date +%Y%m%d%H%M%S)-$(openssl rand -hex 3)"
  RUN_DIR="$ROOT/dist/compatibility/$COMPOSE_PROJECT_NAME"
  mkdir -p "$RUN_DIR/private"
  MINIO_ROOT_USER="compat$(openssl rand -hex 8)"
  MINIO_ROOT_PASSWORD=$(openssl rand -hex 24)
  COMPAT_IAM_SECRET=$(openssl rand -hex 24)
  export COMPAT_PLATFORM=${COMPAT_PLATFORM:-linux/arm64}
  {
    printf 'export COMPOSE_PROJECT_NAME=%q\n' "$COMPOSE_PROJECT_NAME"
    printf 'export MINIO_ROOT_USER=%q\n' "$MINIO_ROOT_USER"
    printf 'export MINIO_ROOT_PASSWORD=%q\n' "$MINIO_ROOT_PASSWORD"
    printf 'export COMPAT_IAM_SECRET=%q\n' "$COMPAT_IAM_SECRET"
    printf 'export COMPAT_PLATFORM=%q\n' "$COMPAT_PLATFORM"
    printf 'BASELINE_IMAGE=%q\n' "$BASELINE_IMAGE"
    printf 'SMALL_OBJECTS=%q\n' "$SMALL_OBJECTS"
    printf 'LARGE_BYTES=%q\n' "$LARGE_BYTES"
  } > "$RUN_DIR/private/environment"
fi
export COMPAT_IMAGE="$BASELINE_IMAGE"
dc() { docker compose -p "$COMPOSE_PROJECT_NAME" -f "$COMPOSE_FILE" "$@"; }
failure() {
  code=$?
  if (( code != 0 )); then
    dc logs --no-color > "$RUN_DIR/failure-server.log" 2>&1 || true
    echo "FAILED; isolated test volume and private credentials retained for diagnosis: $RUN_DIR" >&2
    echo "To remove only this test stack: bash '$RUN_DIR/cleanup.sh'" >&2
  fi
}
trap failure EXIT
{
  printf '#!/usr/bin/env bash\nset -euo pipefail\n'
  printf 'source %q\n' "$RUN_DIR/private/environment"
  printf 'export COMPAT_IMAGE=%q\n' "$BASELINE_IMAGE"
  printf 'docker compose -p %q -f %q down --volumes\n' "$COMPOSE_PROJECT_NAME" "$COMPOSE_FILE"
} > "$RUN_DIR/cleanup.sh"
docker image inspect "$BASELINE_IMAGE" --format '{{.Id}} {{.Architecture}}' > "$RUN_DIR/baseline-image.txt"
if [[ "$MODE" == full || "$MODE" == resume ]]; then docker image inspect "$TARGET_IMAGE" --format '{{.Id}} {{.Architecture}}' > "$RUN_DIR/target-image.txt"; fi
if [[ -n "${COMPAT_DRIVER:-}" ]]; then cp "$COMPAT_DRIVER" "$RUN_DIR/driver"; else go build -o "$RUN_DIR/driver" ./tests/compatibility; fi
mc --version > "$RUN_DIR/mc-version.txt"

ready() {
  export COMPAT_ENDPOINT
  COMPAT_ENDPOINT=$(dc port storage 9000)
  for (( attempt=0; attempt<120; attempt++ )); do
    if curl --fail --silent "http://$COMPAT_ENDPOINT/minio/health/ready" >/dev/null; then return; fi
    sleep 1
  done
  echo 'Server did not become ready in 120 seconds' >&2
  return 1
}
volume() {
  docker inspect "$(dc ps -q storage)" --format '{{range .Mounts}}{{if eq .Destination "/data"}}{{.Name}}{{end}}{{end}}'
}
start_image() {
  export COMPAT_IMAGE=$1
  dc up --detach --force-recreate --pull never
  ready
  volume > "$RUN_DIR/current-volume.txt"
  if [[ -f "$RUN_DIR/original-volume.txt" ]]; then cmp "$RUN_DIR/original-volume.txt" "$RUN_DIR/current-volume.txt"; else cp "$RUN_DIR/current-volume.txt" "$RUN_DIR/original-volume.txt"; fi
}
record_running_image() {
  local actual
  actual=$(docker inspect "$(dc ps -q storage)" --format '{{.Image}}')
  docker image inspect "$actual" --format '{{.Id}} {{.Architecture}}' > "$RUN_DIR/$1-image.txt"
}
run_driver() {
  "$RUN_DIR/driver" -mode "$1" -phase "$2" -manifest "$RUN_DIR/manifest.json" -result "$RUN_DIR/$2.json" -small "$SMALL_OBJECTS" -large-bytes "$LARGE_BYTES" 2>&1 | tee "$RUN_DIR/$2.log"
}
run_mc() {
  local phase=$1
  export MC_HOST_test="http://$MINIO_ROOT_USER:$MINIO_ROOT_PASSWORD@$COMPAT_ENDPOINT"
  mc --config-dir "$RUN_DIR/private/mc" --json admin info test > "$RUN_DIR/$phase-mc-admin-info.json"
  mc --config-dir "$RUN_DIR/private/mc" --json admin user info test compat-reader > "$RUN_DIR/$phase-mc-user-info.json"
  mc --config-dir "$RUN_DIR/private/mc" --json admin policy info test compat-read > "$RUN_DIR/$phase-mc-policy-info.json"
  mc --config-dir "$RUN_DIR/private/mc" --json version info test/compat-versions > "$RUN_DIR/$phase-mc-version-info.json"
  mc --config-dir "$RUN_DIR/private/mc" --json stat test/compat-data/large/multipart-boundary.bin > "$RUN_DIR/$phase-mc-stat.json"
  mc --config-dir "$RUN_DIR/private/mc" --json ls test > "$RUN_DIR/$phase-mc-buckets.json"
  unset MC_HOST_test
}

if [[ "$MODE" != resume ]]; then
  start_image "$BASELINE_IMAGE"
  record_running_image baseline
  if [[ "$MODE" != prepare-resume ]]; then run_driver seed baseline-seed; fi
  run_driver verify baseline-verify
  run_mc baseline
  dc logs --no-color > "$RUN_DIR/baseline-server.log"
  # The config is redacted before persisting; credentials stay in private/environment.
  dc config --format json | python3 -c 'import json,sys; d=json.load(sys.stdin); d["services"]["storage"]["environment"]={k:"<redacted>" if "PASSWORD" in k or "USER" in k else v for k,v in d["services"]["storage"]["environment"].items()};json.dump(d,sys.stdout,indent=2)' > "$RUN_DIR/baseline-compose.json"
  if [[ "$MODE" == prepare || "$MODE" == prepare-resume ]]; then
    dc stop
    echo "Baseline seeded and verified. Resume with: TARGET_IMAGE=$TARGET_IMAGE scripts/test-compatibility.sh resume '$RUN_DIR'"
    exit 0
  fi
fi

start_image "$TARGET_IMAGE"
record_running_image target
dc config --format json | python3 -c 'import json,sys; d=json.load(sys.stdin); d["services"]["storage"]["environment"]={k:"<redacted>" if "PASSWORD" in k or "USER" in k else v for k,v in d["services"]["storage"]["environment"].items()};json.dump(d,sys.stdout,indent=2)' > "$RUN_DIR/target-compose.json"
python3 - "$RUN_DIR" <<'PY'
import json, pathlib, sys
p=pathlib.Path(sys.argv[1]); a=json.loads((p/'baseline-compose.json').read_text()); b=json.loads((p/'target-compose.json').read_text())
old=a['services']['storage'].pop('image'); new=b['services']['storage'].pop('image')
assert a==b, 'Compose configuration changed beyond the image field'
assert old!=new, 'Baseline and target image names must differ'
(p/'compose-image-only-swap.json').write_text(json.dumps({'passed':True,'baselineImage':old,'targetImage':new,'sameVolume':(p/'original-volume.txt').read_text().strip()},indent=2)+'\n')
PY
run_driver verify minigo-swap-verify
run_mc minigo
run_driver write minigo-new-writes
run_driver verify minigo-new-writes-verify
dc logs --no-color > "$RUN_DIR/minigo-server.log"
rm -f "$RUN_DIR/crash-ready"
"$RUN_DIR/driver" -mode crash-write -phase minigo-interrupted-write -ready-file "$RUN_DIR/crash-ready" -manifest "$RUN_DIR/manifest.json" -result "$RUN_DIR/minigo-interrupted-write.json" > "$RUN_DIR/minigo-interrupted-write.log" 2>&1 &
CRASH_WRITER_PID=$!
for (( attempt=0; attempt<30; attempt++ )); do
  [[ -f "$RUN_DIR/crash-ready" ]] && break
  kill -0 "$CRASH_WRITER_PID" || { cat "$RUN_DIR/minigo-interrupted-write.log"; exit 1; }
  sleep 1
done
[[ -f "$RUN_DIR/crash-ready" ]] || { echo 'In-flight writer did not signal readiness' >&2; exit 1; }
kill -0 "$CRASH_WRITER_PID"
dc kill -s SIGKILL storage
wait "$CRASH_WRITER_PID"
dc start storage
ready
cmp "$RUN_DIR/original-volume.txt" <(volume)
run_driver verify minigo-crash-recovery-verify
run_mc minigo-recovered
dc logs --no-color > "$RUN_DIR/minigo-recovered-server.log"
start_image "$BASELINE_IMAGE"
run_driver verify rollback-verify
run_mc rollback
dc logs --no-color > "$RUN_DIR/rollback-server.log"
python3 - "$RUN_DIR" <<'PY'
import json,pathlib,sys,datetime
p=pathlib.Path(sys.argv[1]); phases=['baseline-seed','baseline-verify','minigo-swap-verify','minigo-new-writes','minigo-new-writes-verify','minigo-interrupted-write','minigo-crash-recovery-verify','rollback-verify']
r=[json.loads((p/(phase+'.json')).read_text()) for phase in phases]
assert all(x['passed'] for x in r)
m=json.loads((p/'manifest.json').read_text())
report={'passed':True,'completed':datetime.datetime.now(datetime.timezone.utc).isoformat(),'scope':'single-node single-volume','platform':json.loads((p/'target-compose.json').read_text())['services']['storage']['platform'],'sameVolume':(p/'original-volume.txt').read_text().strip(),'baselineImage':(p/'baseline-image.txt').read_text().strip(),'targetImage':(p/'target-image.txt').read_text().strip(),'largeObjectBytes':max(x['size'] for x in m['objects']),'smallObjects':sum(x['key'].startswith('many-small/') for x in m['objects']),'inventoryEntries':len(m['inventory']),'baselineApiFindings':['Existing MinIO V1/V2 listings omit prefix/file/child when prefix/file also exists; direct SHA256 and version listing preserve access.'],'phases':r,'limitations':['Does not prove distributed erasure-set failures, bit rot recovery, KMS, replication, every S3 extension, or concurrent in-flight acknowledged-write crash safety.','SIGKILL occurs during a slow multipart part request after prior acknowledged writes; all persisted versions are rehashed and the unfinished object must remain absent.','Source images are local and never pulled.']}
(p/'report.json').write_text(json.dumps(report,indent=2)+'\n')
print(json.dumps(report,indent=2))
PY
if [[ "$KEEP_VOLUME" == 1 ]]; then dc stop; else dc down --volumes; fi
echo "Compatibility evidence: $RUN_DIR/report.json"
